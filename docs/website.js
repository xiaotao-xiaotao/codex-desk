// 按实际滚动位置更新当前章节，避免仅点击导航时高亮而手动滚动时失步。
let navigationFrame = 0;
const updateNavigation = () => {
  navigationFrame = 0;
  const boundary = header.getBoundingClientRect().bottom + 32;
  let active;
  navigationLinks.forEach((link) => {
    if (
      document.querySelector(link.hash).getBoundingClientRect().top <= boundary
    )
      active = link;
  });
  if (innerHeight + scrollY >= document.documentElement.scrollHeight - 4)
    active = navigationLinks.at(-1);
  navigationLinks.forEach((link) => {
    if (link === active) link.setAttribute("aria-current", "location");
    else link.removeAttribute("aria-current");
  });
};
window.addEventListener(
  "scroll",
  () => {
    if (!navigationFrame)
      navigationFrame = requestAnimationFrame(updateNavigation);
  },
  { passive: true },
);
window.addEventListener("resize", updateNavigation);
